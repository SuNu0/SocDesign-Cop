 @(posedge clk);@(negedge clk);rsp_ready=0;
 @(posedge clk);@(negedge clk);cmd_valid=0;
 if(rsp_valid!==1 || rsp_rdata!==64)$fatal(1,"queued K response");
 rsp_ready=1;@(posedge clk);@(negedge clk);rsp_ready=0;
end endtask
